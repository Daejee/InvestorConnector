# Split into batches of 50 rows to avoid timeout
def process_in_batches(data, batch_size=50):
    lines = data.strip().split('\n')
    header = lines[0]
    
    for i in range(1, len(lines), batch_size):
        batch_lines = lines[i:i+batch_size]
        batch_data = header + '\n' + '\n'.join(batch_lines)
        
        # Write to temp file
        filename = f'batch_{i//batch_size + 1}.csv'
        with open(filename, 'w', encoding='utf-8') as f:
            f.write(batch_data)
            
        # Upload batch
        try:
            with open(filename, 'rb') as f:
                response = requests.post(
                    'http://localhost:5000/api/investors/upload-csv',
                    files={'file': f}
                )
            print(f"Batch {i//batch_size + 1}: {response.json()}")
        except Exception as e:
            print(f"Batch {i//batch_size + 1} failed: {e}")

if __name__ == '__main__':
    process_in_batches(csv_data, 50)